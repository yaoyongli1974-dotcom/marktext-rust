#!/usr/bin/env python3
"""Generate the Unicode category tables the Markdown engine needs.

CommonMark 0.31.2 defines a *Unicode punctuation character* as a character in
the Unicode ``P`` (punctuation) **or** ``S`` (symbol) general categories.
MarkText's own inline parser uses the same definition (``/[\\p{P}\\p{S}]/u``),
so the Rust engine needs the very same classification.

The table is written as sorted, non-overlapping ranges so that the lookup is a
binary search.  Run the script after a Unicode upgrade:

    python scripts/generate-unicode-tables.py
"""

from __future__ import annotations

import unicodedata
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "crates" / "marktext-core" / "src" / "unicode.rs"

#: The general categories that count as punctuation for the flanking rules.
PUNCTUATION_CATEGORIES = {"Pc", "Pd", "Pe", "Pf", "Pi", "Po", "Ps",
                          "Sm", "Sc", "Sk", "So"}

#: The general categories that count as whitespace.
WHITESPACE_CATEGORIES = {"Zs"}


def ranges_for(categories: set[str]) -> list[tuple[int, int]]:
    """Collect the code point ranges that belong to one of `categories`."""
    ranges: list[tuple[int, int]] = []
    start: int | None = None
    previous = -1
    for code_point in range(0x110000):
        char = chr(code_point)
        if unicodedata.category(char) in categories:
            if start is None:
                start = code_point
            previous = code_point
        elif start is not None:
            ranges.append((start, previous))
            start = None
    if start is not None:
        ranges.append((start, previous))
    return ranges


def render(name: str, ranges: list[tuple[int, int]], doc: str) -> str:
    lines = [f"/// {doc}", f"const {name}: [(u32, u32); {len(ranges)}] = ["]
    for start, end in ranges:
        lines.append(f"    (0x{start:04X}, 0x{end:04X}),")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    punctuation = ranges_for(PUNCTUATION_CATEGORIES)
    whitespace = ranges_for(WHITESPACE_CATEGORIES)

    body = [
        "//! Unicode character classification for the inline parser.",
        "//!",
        "//! The tables are generated by `scripts/generate-unicode-tables.py`",
        "//! from the Unicode character database and must not be edited by hand.",
        "",
        "/// Whether the code point belongs to one of the ranges.",
        "fn in_ranges(table: &[(u32, u32)], code_point: u32) -> bool {",
        "    let mut low = 0usize;",
        "    let mut high = table.len();",
        "    while low < high {",
        "        let middle = (low + high) / 2;",
        "        let (start, end) = table[middle];",
        "        if code_point < start {",
        "            high = middle;",
        "        } else if code_point > end {",
        "            low = middle + 1;",
        "        } else {",
        "            return true;",
        "        }",
        "    }",
        "    false",
        "}",
        "",
    ]
    body.append(render(
        "PUNCTUATION_RANGES",
        punctuation,
        "The code points of the Unicode `P` (punctuation) and `S` (symbol)\n"
        "/// general categories, which CommonMark 0.31.2 counts as punctuation.",
    ))
    body.append(render(
        "WHITESPACE_RANGES",
        whitespace,
        "The code points of the Unicode `Zs` (space separator) general category.",
    ))

    TARGET.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {TARGET} ({len(punctuation)} punctuation ranges, "
          f"{len(whitespace)} whitespace ranges)")


if __name__ == "__main__":
    main()
